-- RLS Policies

-- 1. Departments Policies
CREATE POLICY "Allow select for authenticated and anon" ON public.departments FOR SELECT USING (true);
CREATE POLICY "Allow admin write" ON public.departments FOR ALL TO authenticated USING ((auth.jwt() -> 'user_metadata' ->> 'role') = 'admin') WITH CHECK ((auth.jwt() -> 'user_metadata' ->> 'role') = 'admin');

-- 2. Employees Policies
CREATE POLICY "Allow select for own profile or admin" ON public.employees FOR SELECT TO authenticated USING (email = auth.jwt() ->> 'email' OR (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin');
CREATE POLICY "Allow admin write" ON public.employees FOR ALL TO authenticated USING ((auth.jwt() -> 'user_metadata' ->> 'role') = 'admin') WITH CHECK ((auth.jwt() -> 'user_metadata' ->> 'role') = 'admin');

-- 3. Attendance Policies
CREATE POLICY "Allow select for own attendance or admin" ON public.attendance FOR SELECT TO authenticated USING (employee_id = (SELECT id FROM public.employees WHERE email = auth.jwt() ->> 'email') OR (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin');
-- Write is service_role only (no INSERT/UPDATE/DELETE policies for public or authenticated).

