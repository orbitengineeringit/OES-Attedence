-- Supabase Migration Schema
-- Run this in the Supabase Dashboard SQL Editor

-- 1. Departments Table
CREATE TABLE IF NOT EXISTS public.departments (
  id VARCHAR(50) PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  code VARCHAR(50) NOT NULL,
  description TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Employees Table
CREATE TABLE IF NOT EXISTS public.employees (
  id VARCHAR(50) PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) UNIQUE NOT NULL,
  password TEXT NOT NULL,
  role VARCHAR(50) NOT NULL,
  department VARCHAR(100) NOT NULL,
  avatar TEXT,
  profile_image TEXT,
  face_data TEXT,
  status VARCHAR(50) DEFAULT 'Offline',
  latitude DOUBLE PRECISION DEFAULT 0.0,
  longitude DOUBLE PRECISION DEFAULT 0.0,
  last_latitude DOUBLE PRECISION DEFAULT 0.0,
  last_longitude DOUBLE PRECISION DEFAULT 0.0,
  last_location_time TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Attendance Table
CREATE TABLE IF NOT EXISTS public.attendance (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id VARCHAR(50) NOT NULL REFERENCES public.employees(id) ON DELETE CASCADE,
  date VARCHAR(20) NOT NULL,
  check_in VARCHAR(20),
  check_out VARCHAR(20),
  working_hours DOUBLE PRECISION DEFAULT 0,
  break_duration DOUBLE PRECISION DEFAULT 0,
  overtime DOUBLE PRECISION DEFAULT 0,
  status VARCHAR(50),
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  confidence_score DOUBLE PRECISION,
  captured_image TEXT,
  device_id VARCHAR(100),
  UNIQUE(employee_id, date)
);

-- 4. Attendance Corrections Table
CREATE TABLE IF NOT EXISTS public.attendance_corrections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attendance_id INT NOT NULL,
  employee_id VARCHAR(50) NOT NULL,
  corrected_by VARCHAR(50) NOT NULL,
  reason TEXT NOT NULL,
  old_values JSONB,
  new_values JSONB,
  corrected_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Face Descriptors Table
CREATE TABLE IF NOT EXISTS public.face_descriptors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id VARCHAR(50) UNIQUE NOT NULL REFERENCES public.employees(id) ON DELETE CASCADE,
  descriptor_json TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Devices Table
CREATE TABLE IF NOT EXISTS public.devices (
  id VARCHAR(100) PRIMARY KEY,
  device_name VARCHAR(100) NOT NULL,
  device_ip VARCHAR(50),
  mac_address VARCHAR(50),
  status VARCHAR(50) DEFAULT 'Active',
  last_seen TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Audit Logs Table
CREATE TABLE IF NOT EXISTS public.audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id VARCHAR(50),
  event_type VARCHAR(100) NOT NULL,
  details TEXT,
  ip_address VARCHAR(50),
  timestamp TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Logs Table
CREATE TABLE IF NOT EXISTS public.logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id VARCHAR(50) REFERENCES public.employees(id) ON DELETE SET NULL,
  event_type VARCHAR(100) NOT NULL,
  timestamp TIMESTAMPTZ DEFAULT NOW(),
  location VARCHAR(255),
  details TEXT
);

-- 9. Locations Table
CREATE TABLE IF NOT EXISTS public.locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  radius_meters INT DEFAULT 100,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Settings Table
CREATE TABLE IF NOT EXISTS public.settings (
  key VARCHAR(100) PRIMARY KEY,
  value TEXT NOT NULL
);

-- 11. Office Geofence Table
CREATE TABLE IF NOT EXISTS public.office_geofence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  office_name VARCHAR(100) NOT NULL,
  polygon_coordinates JSONB NOT NULL,
  created_by VARCHAR(50),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

