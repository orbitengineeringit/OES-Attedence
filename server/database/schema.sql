-- Row Level Security (RLS)
-- We enable RLS on all tables to enforce strict security boundaries.
-- Note: Supabase bypasses RLS for service_role automatically.
-- We do NOT add public permissions on biometric tables.
ALTER TABLE public.departments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.employees ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.attendance ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.attendance_corrections ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.face_descriptors ENABLE ROW LEVEL SECURITY;
